/**
 * Writes server/sql/008_file_maintenance_data.sql from the File Maintenance lists in
 * the database server/.env points at (normally the live "bridge"), so the same lists can
 * be committed and loaded into a dev database.
 *
 * Exported: Type of Contract, Industry Type (application_types), Requirement Categories,
 * Requirements (non-ad-hoc only) and each requirement's contract types. Building and
 * Land Use are included too, but are empty while File Maintenance has none.
 *
 * Rows are matched by name / code, never by id - ids differ between databases, so the
 * generated script resolves category and contract-type links by name on the target.
 *
 * Read-only against the source database. Re-run whenever the lists change:
 *   node server/scripts/export-file-maintenance-sql.js
 */
const fs = require("fs");
const path = require("path");
const { selectData } = require("../config/database");

const OUT = path.join(__dirname, "..", "sql", "008_file_maintenance_data.sql");

const str = (v) => (v === null || v === undefined ? "NULL" : `N'${String(v).replace(/'/g, "''")}'`);
const bit = (v) => (v ? "1" : "0");

function values(rows, toTuple) {
  if (!rows.length) return null;
  return rows.map((r) => `  (${toTuple(r).join(", ")})`).join(",\n");
}

function assertUnique(rows, key, table) {
  const seen = new Set();
  for (const r of rows) {
    const k = String(r[key]).trim().toUpperCase();
    if (seen.has(k)) throw new Error(`${table}: duplicate ${key} "${r[key]}" - fix it in File Maintenance first`);
    seen.add(k);
  }
}

async function run() {
  const [db] = await selectData("SELECT DB_NAME() AS name");
  const contractTypes = await selectData("SELECT name, is_active FROM dbo.type_of_contract ORDER BY name");
  const appTypes = await selectData("SELECT code, name, description, is_active FROM dbo.application_types ORDER BY code");
  const categories = await selectData(
    "SELECT name, description, is_active, deactivated_via_cascade FROM dbo.requirement_categories ORDER BY name"
  );
  const requirements = await selectData(`
    SELECT r.code, r.name, r.description, c.name AS category_name, r.for_new, r.for_renewal,
           r.is_mandatory, r.is_active, r.deactivated_via_cascade
    FROM dbo.requirements r
    LEFT JOIN dbo.requirement_categories c ON c.id = r.category_id
    WHERE r.is_ad_hoc = 0
    ORDER BY r.code`);
  const reqContractTypes = await selectData(`
    SELECT r.code AS requirement_code, t.name AS contract_type_name
    FROM dbo.requirement_contract_types rct
    JOIN dbo.requirements r ON r.id = rct.requirement_id AND r.is_ad_hoc = 0
    JOIN dbo.type_of_contract t ON t.id = rct.contract_type_id
    ORDER BY r.code, t.name`);
  const buildings = await selectData("SELECT name, is_active FROM dbo.building ORDER BY name");
  const landUses = await selectData("SELECT name, is_active FROM dbo.land_use ORDER BY name");

  assertUnique(contractTypes, "name", "type_of_contract");
  assertUnique(appTypes, "code", "application_types");
  assertUnique(categories, "name", "requirement_categories");
  assertUnique(requirements, "code", "requirements");
  assertUnique(buildings, "name", "building");
  assertUnique(landUses, "name", "land_use");

  // Simple name + is_active lists share one upsert shape.
  const nameList = (table, rows) => {
    const v = values(rows, (r) => [str(r.name), bit(r.is_active)]);
    if (!v) return `-- dbo.${table}: no rows in the source database.\n`;
    return `-- dbo.${table} (${rows.length}) --------------------------------------------------
DECLARE @${table} TABLE (name NVARCHAR(255) NOT NULL, is_active BIT NOT NULL);
INSERT @${table} (name, is_active) VALUES
${v};

UPDATE t SET is_active = s.is_active, updated_at = SYSUTCDATETIME()
FROM dbo.${table} t JOIN @${table} s ON s.name = t.name
WHERE t.is_active <> s.is_active;

INSERT dbo.${table} (name, is_active)
SELECT s.name, s.is_active FROM @${table} s
WHERE NOT EXISTS (SELECT 1 FROM dbo.${table} t WHERE t.name = s.name);
`;
  };

  const sqlText = `/*
  008 - File Maintenance data (Type of Contract, Industry Type, Requirement Categories,
        Requirements + their contract types, Building, Land Use)

  GENERATED by server/scripts/export-file-maintenance-sql.js from database "${db.name}"
  on ${new Date().toISOString()}. Do not edit by hand - change the lists in File
  Maintenance and re-run the generator.

  Idempotent: safe to run any number of times. Run it against the target (dev) database:
      sqlcmd -S <server> -d <database> -f 65001 -i server\\sql\\008_file_maintenance_data.sql

  What it does (all in one transaction - any error rolls everything back)
    - Rows are matched by name (code for Industry Type / Requirements), never by id.
    - Missing rows are inserted; existing rows are updated to match this file.
    - Nothing is deleted. Rows that exist only in the target are left alone, and a
      requirement's extra contract types in the target are kept (additive, like the
      app's own requirement sync).
  Prerequisite: the tables must exist - start the backend once against the target
  database first (each model's ensureSchema creates them).
  Afterwards restart the backend so open applications pick up the requirements
  (syncRequirementsFromCatalog runs on boot).
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

IF OBJECT_ID('dbo.type_of_contract', 'U') IS NULL OR OBJECT_ID('dbo.application_types', 'U') IS NULL
   OR OBJECT_ID('dbo.requirement_categories', 'U') IS NULL OR OBJECT_ID('dbo.requirements', 'U') IS NULL
   OR OBJECT_ID('dbo.requirement_contract_types', 'U') IS NULL
   OR OBJECT_ID('dbo.building', 'U') IS NULL OR OBJECT_ID('dbo.land_use', 'U') IS NULL
BEGIN
  RAISERROR('File Maintenance tables are missing - start the backend once against this database, then re-run.', 16, 1);
  RETURN;
END

BEGIN TRANSACTION;

${nameList("type_of_contract", contractTypes)}
-- dbo.application_types - Industry Type (${appTypes.length}) ------------------------------
DECLARE @application_types TABLE (code NVARCHAR(100) NOT NULL, name NVARCHAR(255) NOT NULL, description NVARCHAR(MAX) NULL, is_active BIT NOT NULL);
INSERT @application_types (code, name, description, is_active) VALUES
${values(appTypes, (r) => [str(r.code), str(r.name), str(r.description), bit(r.is_active)])};

UPDATE t SET name = s.name, description = s.description, is_active = s.is_active, updated_at = SYSUTCDATETIME()
FROM dbo.application_types t JOIN @application_types s ON s.code = t.code
WHERE t.name <> s.name OR ISNULL(t.description, N'') <> ISNULL(s.description, N'') OR t.is_active <> s.is_active;

INSERT dbo.application_types (code, name, description, is_active)
SELECT s.code, s.name, s.description, s.is_active FROM @application_types s
WHERE NOT EXISTS (SELECT 1 FROM dbo.application_types t WHERE t.code = s.code);

-- dbo.requirement_categories (${categories.length}) ----------------------------------------
DECLARE @requirement_categories TABLE (name NVARCHAR(255) NOT NULL, description NVARCHAR(MAX) NULL, is_active BIT NOT NULL, deactivated_via_cascade BIT NOT NULL);
INSERT @requirement_categories (name, description, is_active, deactivated_via_cascade) VALUES
${values(categories, (r) => [str(r.name), str(r.description), bit(r.is_active), bit(r.deactivated_via_cascade)])};

UPDATE t SET description = s.description, is_active = s.is_active, deactivated_via_cascade = s.deactivated_via_cascade, updated_at = SYSUTCDATETIME()
FROM dbo.requirement_categories t JOIN @requirement_categories s ON s.name = t.name
WHERE ISNULL(t.description, N'') <> ISNULL(s.description, N'') OR t.is_active <> s.is_active OR t.deactivated_via_cascade <> s.deactivated_via_cascade;

INSERT dbo.requirement_categories (name, description, is_active, deactivated_via_cascade)
SELECT s.name, s.description, s.is_active, s.deactivated_via_cascade FROM @requirement_categories s
WHERE NOT EXISTS (SELECT 1 FROM dbo.requirement_categories t WHERE t.name = s.name);

-- dbo.requirements (${requirements.length}) - category resolved by name ----------------------
DECLARE @requirements TABLE (code NVARCHAR(100) NOT NULL, name NVARCHAR(500) NOT NULL, description NVARCHAR(MAX) NULL, category_name NVARCHAR(255) NULL,
  for_new BIT NOT NULL, for_renewal BIT NOT NULL, is_mandatory BIT NOT NULL, is_active BIT NOT NULL, deactivated_via_cascade BIT NOT NULL);
INSERT @requirements (code, name, description, category_name, for_new, for_renewal, is_mandatory, is_active, deactivated_via_cascade) VALUES
${values(requirements, (r) => [
  str(r.code), str(r.name), str(r.description), str(r.category_name),
  bit(r.for_new), bit(r.for_renewal), bit(r.is_mandatory), bit(r.is_active), bit(r.deactivated_via_cascade),
])};

UPDATE t SET name = s.name, description = s.description, category_id = c.id, for_new = s.for_new, for_renewal = s.for_renewal,
  is_mandatory = s.is_mandatory, is_active = s.is_active, deactivated_via_cascade = s.deactivated_via_cascade, updated_at = SYSUTCDATETIME()
FROM dbo.requirements t
JOIN @requirements s ON s.code = t.code
LEFT JOIN dbo.requirement_categories c ON c.name = s.category_name
WHERE t.is_ad_hoc = 0
  AND (t.name <> s.name OR ISNULL(t.description, N'') <> ISNULL(s.description, N'') OR ISNULL(t.category_id, -1) <> ISNULL(c.id, -1)
       OR t.for_new <> s.for_new OR t.for_renewal <> s.for_renewal OR t.is_mandatory <> s.is_mandatory
       OR t.is_active <> s.is_active OR t.deactivated_via_cascade <> s.deactivated_via_cascade);

INSERT dbo.requirements (code, name, description, category_id, for_new, for_renewal, is_mandatory, is_active, is_ad_hoc, deactivated_via_cascade, created_at)
SELECT s.code, s.name, s.description, c.id, s.for_new, s.for_renewal, s.is_mandatory, s.is_active, 0, s.deactivated_via_cascade, SYSUTCDATETIME()
FROM @requirements s
LEFT JOIN dbo.requirement_categories c ON c.name = s.category_name
WHERE NOT EXISTS (SELECT 1 FROM dbo.requirements t WHERE t.code = s.code);

-- dbo.requirement_contract_types (${reqContractTypes.length}) - by requirement code + contract name
DECLARE @requirement_contract_types TABLE (requirement_code NVARCHAR(100) NOT NULL, contract_type_name NVARCHAR(255) NOT NULL);
INSERT @requirement_contract_types (requirement_code, contract_type_name) VALUES
${values(reqContractTypes, (r) => [str(r.requirement_code), str(r.contract_type_name)])};

INSERT dbo.requirement_contract_types (requirement_id, contract_type_id)
SELECT DISTINCT r.id, t.id
FROM @requirement_contract_types s
JOIN dbo.requirements r ON r.code = s.requirement_code AND r.is_ad_hoc = 0
JOIN dbo.type_of_contract t ON t.name = s.contract_type_name
WHERE NOT EXISTS (SELECT 1 FROM dbo.requirement_contract_types x WHERE x.requirement_id = r.id AND x.contract_type_id = t.id);

${nameList("building", buildings)}
${nameList("land_use", landUses)}
COMMIT TRANSACTION;

-- Verify -----------------------------------------------------------------------
SELECT 'type_of_contract' AS tbl, COUNT(*) AS rows FROM dbo.type_of_contract
UNION ALL SELECT 'application_types', COUNT(*) FROM dbo.application_types
UNION ALL SELECT 'requirement_categories', COUNT(*) FROM dbo.requirement_categories
UNION ALL SELECT 'requirements (non-ad-hoc)', COUNT(*) FROM dbo.requirements WHERE is_ad_hoc = 0
UNION ALL SELECT 'requirement_contract_types', COUNT(*) FROM dbo.requirement_contract_types
UNION ALL SELECT 'building', COUNT(*) FROM dbo.building
UNION ALL SELECT 'land_use', COUNT(*) FROM dbo.land_use;
`;

  // BOM so SSMS reads any non-ASCII names as UTF-8, not the ANSI codepage.
  fs.writeFileSync(OUT, "﻿" + sqlText, "utf8");
  console.log(`Wrote ${path.relative(process.cwd(), OUT)} from "${db.name}":`);
  console.log(
    `  type_of_contract ${contractTypes.length}, application_types ${appTypes.length}, requirement_categories ${categories.length},` +
      ` requirements ${requirements.length}, requirement_contract_types ${reqContractTypes.length},` +
      ` building ${buildings.length}, land_use ${landUses.length}`
  );
}

run()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error(err);
    process.exit(1);
  });
